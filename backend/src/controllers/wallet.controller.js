const getBalance = async (req, res, next) => {
  try {
    const wallet = await Wallet.findOne({ user: req.user._id });
    return res.json({
      success: true,
      data: {
        balance: wallet ? wallet.balance : 0,
        commissionBalance: wallet ? wallet.commissionBalance : 0,
      },
    });
  } catch (error) {
    return next(error);
  }
};

const getTransactions = async (req, res, next) => {
  try {
    const { type, page = 1, limit = 20 } = req.query;
    const filter = { user: req.user._id };
    if (type) filter.type = type;

    const list = await Transaction.find(filter)
      .sort({ createdAt: -1 })
      .skip((page - 1) * limit)
      .limit(Number(limit));

    return res.json({ success: true, data: list });
  } catch (error) {
    return next(error);
  }
};

const requestDeposit = async (req, res, next) => {
  try {
    let { amount, channel, method, reference, proofUrl, depositId } = req.body;

    if (depositId) {
      const deposit = await Deposit.findById(depositId);
      if (!deposit) return res.status(404).json({ message: "Deposit not found." });

      deposit.txHash = reference || "";
      deposit.proofImage = proofUrl || "";
      await deposit.save();

      // Send Telegram "Created👀" notification with updated TxID
      const { sendTelegramNotification } = require("../utils/telegram");
      await sendTelegramNotification(deposit, req.user, "created");

      logger.info(`Deposit proof submitted for deposit ${deposit._id} with TxID: ${reference}`);

      return res.json({
        success: true,
        data: {
          depositId: deposit._id,
          amount: deposit.amount,
          channel: deposit.channel,
          address: deposit.address,
        },
      });
    }

    if (!channel && method) {
      const parts = method.split("-");
      channel = parts.slice(1).join("-"); // e.g. "usdt-trc20"
    }

    if (channel) {
      if (channel.toLowerCase().includes("trc20")) channel = "TRC20";
      else if (channel.toLowerCase().includes("bep20")) channel = "BEP20";
    }

    if (!amount || !channel) {
      return res.status(400).json({ message: "Amount and channel network are required." });
    }

    const config = await PlatformConfig.findOne() || new PlatformConfig();

    let targetAddress = "";
    
    // Look up rotating address list first
    const rotatingList = await UsdtAddress.find({ network: channel, isActive: true });
    
    if (rotatingList && rotatingList.length > 0) {
      // Rotate by selecting the address with the lowest useCount
      const chosen = rotatingList.sort((a, b) => a.useCount - b.useCount)[0];
      targetAddress = chosen.address;
      
      // Increment use count
      chosen.useCount += 1;
      await chosen.save();
    } else {
      // Fallback to default configs if rotating list is empty
      if (channel === "TRC20" && config.enableTRC20) {
        targetAddress = config.usdt_trc20;
      } else if (channel === "BEP20" && config.enableBEP20) {
        targetAddress = config.usdt_bep20;
      } else if (channel === "ERC20" && config.enableERC20) {
        targetAddress = config.usdt_erc20;
      } else {
        return res.status(400).json({ message: `Deposit channel ${channel} is currently disabled or unsupported.` });
      }
    }

    const deposit = new Deposit({
      user: req.user._id,
      amount,
      channel,
      status: "pending",
      address: targetAddress,
      txHash: reference || "",
      proofImage: proofUrl || "",
    });
    await deposit.save();

    // Trigger Telegram notification for created state on manual wagers
    try {
      const { sendTelegramNotification } = require("../utils/telegram");
      await sendTelegramNotification(deposit, req.user, "created");
    } catch (tgErr) {
      logger.error("Failed to send manual Telegram created notification:", tgErr);
    }

    logger.info(`Deposit request generated by ${req.user.mobile} for ₹${amount} via ${channel}`);

    return res.status(201).json({
      success: true,
      data: {
        depositId: deposit._id,
        amount: deposit.amount,
        channel: deposit.channel,
        address: targetAddress,
      },
    });
  } catch (error) {
    return next(error);
  }
};

